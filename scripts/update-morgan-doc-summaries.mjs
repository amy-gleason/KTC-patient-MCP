console.log(`Fetching bundle from ${JWE_URL}...`);
const res = await fetch(JWE_URL, { cache: "no-store" });
if (!res.ok) {
  console.error(`Failed to fetch bundle: HTTP ${res.status}`);
  process.exit(1);
}
const bundle = JSON.parse(decryptJwe(await res.text(), KEY).toString("utf8"));
console.log(`Bundle: ${bundle.entry.length} entries`);

// Index DocRefs by filename (last URL segment)
const drByFilename = new Map();
for (const e of bundle.entry ?? []) {
  const dr = e.resource;
  if (dr?.resourceType !== "DocumentReference") continue;
  for (const c of dr.content ?? []) {
    const a = c.attachment;
    if (!a?.url) continue;
    const filename = a.url.split("/").pop();
    if (!drByFilename.has(filename)) drByFilename.set(filename, []);
    drByFilename.get(filename).push(dr);
  }
}

// Also collect ALL DocRef filenames for fuzzy fallback
const allFilenames = Array.from(drByFilename.keys());

function tokens(name) {
  return name
    .toLowerCase()
    .replace(/\.pdf$/i, "")
    .split(/[^a-z0-9]+/)
    .filter(Boolean);
}
function fuzzyScore(a, b) {
  const A = new Set(tokens(a));
  const B = new Set(tokens(b));
  let common = 0;
  for (const t of A) if (B.has(t)) common++;
  return common / Math.max(A.size, B.size);
}

let updated = 0;
const unmatched = [];
for (const u of UPDATES) {
  let matches = drByFilename.get(u.filename);
  let matchedFilename = u.filename;
  if (!matches) {
    // Fuzzy fallback
    let best = null;
    let bestScore = 0;
    for (const cand of allFilenames) {
      const s = fuzzyScore(u.filename, cand);
      if (s > bestScore) {
        bestScore = s;
        best = cand;
      }
    }
    if (best && bestScore >= 0.5) {
      matches = drByFilename.get(best);
      matchedFilename = best;
      console.log(`  ~ fuzzy: ${u.filename} → ${best} (score ${bestScore.toFixed(2)})`);
    }
  }
  if (!matches?.length) {
    console.warn(`  ! no DocRef found for ${u.filename}`);
    unmatched.push(u.filename);
    continue;
  }
  for (const dr of matches) {
    if (u.description) dr.description = u.description;
    if (u.title) {
      // DocumentReference has no direct title; title is conventionally set on
      // content[].attachment.title. Update the first attachment.
      const att = dr.content?.[0]?.attachment;
      if (att) att.title = u.title;
    }
  }
  console.log(`  ✓ updated ${matchedFilename} (${matches.length} DocRef${matches.length > 1 ? "s" : ""})`);
  updated++;
}

console.log(`\n${updated}/${UPDATES.length} DocRefs updated. ${unmatched.length} unmatched.`);
if (unmatched.length) {
  console.log(`Unmatched:\n  ${unmatched.join("\n  ")}`);
}

if (!APPLY) {
  console.log(`\nDry-run. Re-run with --apply to write ${JWE_PATH}.`);
  process.exit(0);
}

bundle.timestamp = new Date().toISOString();
const bundleJson = JSON.stringify(bundle);
console.log(`\nBundle JSON size: ${(bundleJson.length / 1024 / 1024).toFixed(2)} MB`);

const newJwe = encryptJwe(Buffer.from(bundleJson, "utf8"), KEY, {
  cty: "application/fhir+json",
});
console.log(`Encrypted JWE size: ${(newJwe.length / 1024 / 1024).toFixed(2)} MB`);

writeFileSync(JWE_PATH, newJwe);
console.log(`\n✓ Wrote ${JWE_PATH}`);
